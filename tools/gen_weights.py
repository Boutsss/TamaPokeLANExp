#!/usr/bin/env python3
"""Species weights, for LOW KICK, GRASS KNOT, HEAVY SLAM and HEAT CRASH.

    python3 tools/gen_weights.py DIR   # DIR holds PokeAPI /pokemon/<n> as p<n>.json
    python3 tools/gen_weights.py       # just regenerate weights.h from dex_weights.py

PokeAPI gives weight in hectograms (SNORLAX = 4600, i.e. 460.0 kg); kept as is.
The data lands in tools/dex_weights.py (committed), so a rebuild needs no network.
"""
import json, os, sys
HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
from dex_data import DEX
N = len(DEX)
if len(sys.argv) > 1:
    w = []
    for i in range(1, N + 1):
        with open(os.path.join(sys.argv[1], 'p%d.json' % i)) as f:
            w.append(int(json.load(f)['weight']))
    if len(w) != N or min(w) < 1: sys.exit('incomplete fetch -- nothing written')
    with open(os.path.join(HERE, 'dex_weights.py'), 'w') as f:
        f.write('# GENERATED by tools/gen_weights.py from PokeAPI /pokemon -- hectograms, dex order from 1\n')
        f.write('WEIGHTS = %r\n' % w)
from dex_weights import WEIGHTS
assert len(WEIGHTS) == N, 'dex_weights.py is out of step with DEX_COUNT -- re-fetch'
with open(os.path.join(HERE, '..', 'weights.h'), 'w') as f:
    f.write('#pragma once\n#include <stdint.h>\n\n// GENERATED by tools/gen_weights.py - do not edit.\n')
    f.write('// Species weight in hectograms (0.1 kg), DEX_WEIGHT[dex]; [0] unused.\n')
    f.write('static const uint16_t DEX_WEIGHT[%d] = {\n  0,\n' % (N + 1))
    for i in range(0, N, 16):
        f.write('  ' + ' '.join('%d,' % x for x in WEIGHTS[i:i + 16]) + '\n')
    f.write('};\n')
print('weights.h: %d species, SNORLAX %d' % (N, WEIGHTS[142]))
