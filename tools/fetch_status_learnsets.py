#!/usr/bin/env python3
"""Who can learn the six STATUS moves (v3.33), and their official names.

    python3 tools/fetch_status_learnsets.py

Reads /move/<slug> from PokeAPI -- six requests, not one per species -- and
writes tools/dex_learnsets_tm.py: every species that can learn the move in ANY
game, as a TM-style entry (level 0). The firmware gates every level-0 entry at
TM_LEVEL (pet.cpp), so none of these reaches a creature before level 40, and
the move picker lists them only from then on.

gen_moves.py merges these into LEARNSETS. fetch_pokeapi.py's own output is
left alone, so re-running either tool cannot lose the other's entries.

It also prints each move's ES/FR/DE/IT names (accents folded for the bitmap
font) for tools/dex_move_names.py.
"""
import json, os, subprocess, sys, unicodedata

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
from dex_data import DEX

STATUS = ['thunder-wave', 'sleep-powder', 'hypnosis', 'toxic', 'will-o-wisp', 'confuse-ray']

def get(url):
    out = subprocess.run(['curl', '-sf', '--max-time', '30', url], capture_output=True, check=True).stdout
    return json.loads(out)

def fold(s):
    s = unicodedata.normalize('NFKD', s)
    return ''.join(c for c in s if not unicodedata.combining(c)).upper()

def main():
    dex_count = len(DEX)
    learners = {}
    for slug in STATUS:
        d = get('https://pokeapi.co/api/v2/move/%s/' % slug)
        n = 0
        for p in d['learned_by_pokemon']:
            num = int(p['url'].rstrip('/').split('/')[-1])
            if 1 <= num <= dex_count:          # forms (10000+) are not separate species here
                learners.setdefault(num, []).append((slug, 0))
                n += 1
        names = {x['language']['name']: x['name'] for x in d['names']}
        print('%-13s %4d species   ES %-14s FR %-14s DE %-14s IT %s' % (
            slug, n, fold(names.get('es', '')), fold(names.get('fr', '')), fold(names.get('de', '')), fold(names.get('it', ''))))
    if sum(len(v) for v in learners.values()) < 300:
        sys.exit('suspiciously few learners -- a partial fetch is not data; nothing written')
    with open(os.path.join(HERE, 'dex_learnsets_tm.py'), 'w') as f:
        f.write('# GENERATED by tools/fetch_status_learnsets.py from PokeAPI - do not edit\n')
        f.write('# num -> [(status move slug, 0)]: TM-style entries for the six status moves.\n')
        f.write('LEARNSETS_TM = {\n')
        for num in sorted(learners):
            f.write('    %d: %r,\n' % (num, sorted(learners[num])))
        f.write('}\n')
    print('wrote dex_learnsets_tm.py: %d species' % len(learners))

if __name__ == '__main__':
    main()
