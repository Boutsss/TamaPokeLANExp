#!/usr/bin/env python3
"""Who learns the Gen 1-7 moves (tools/dex_moves_more.py), and at what level.

    python3 tools/fetch_more_learnsets.py            # dex_moves_more.py  -> dex_learnsets_more.py
    python3 tools/fetch_more_learnsets.py --batch 2  # dex_moves_more2.py -> dex_learnsets_more2.py

Fetches every species from PokeAPI into the same cache fetch_pokeapi.py uses
(tools/pokeapi_cache/, gitignored; in parallel, the first run is ~200 MB),
and applies fetch_pokeapi.learn_rows() -- THE level rule, the same version
group per generation and the same TM handling -- to the new moves only.

Writes tools/dex_learnsets_more.py, which gen_moves.py appends after each
species' own rows. The existing learnsets are not regenerated, so nothing a
species already learned moves or changes level.
"""
import os, sys
from concurrent.futures import ThreadPoolExecutor
HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import fetch_pokeapi as fp
BATCH2 = '--batch' in sys.argv and sys.argv[sys.argv.index('--batch') + 1] == '2'
if BATCH2:
    from dex_moves_more2 import MORE2_MOVES as MORE_MOVES
else:
    from dex_moves_more import MORE_MOVES

def main():
    wanted = {slug for _n, slug, *_ in MORE_MOVES}
    nums = list(range(1, fp.DEX_COUNT + 1))
    with ThreadPoolExecutor(max_workers=12) as ex:
        data = dict(zip(nums, ex.map(fp.fetch, nums)))
    missing = set(wanted)
    learn = {}
    for n in nums:
        rows = fp.learn_rows(n, data[n], wanted, missing)
        if rows:
            learn[n] = rows
    total = sum(len(v) for v in learn.values())
    if total < (1500 if BATCH2 else 2000):
        sys.exit('only %d rows -- a partial fetch is not data; nothing written' % total)
    out, var, src = (('dex_learnsets_more2.py', 'LEARNSETS_MORE2', 'dex_moves_more2.py') if BATCH2 else
                     ('dex_learnsets_more.py', 'LEARNSETS_MORE', 'dex_moves_more.py'))
    with open(os.path.join(HERE, out), 'w') as f:
        f.write('# GENERATED by tools/fetch_more_learnsets.py from PokeAPI - do not edit\n')
        f.write('# num -> [(slug, level)] for the Gen 1-7 moves in %s only.\n' % src)
        f.write('%s = {\n' % var)
        for n in sorted(learn):
            f.write('    %d: %r,\n' % (n, learn[n]))
        f.write('}\n')
    lv = sum(1 for v in learn.values() for _s, l in v if l > 0)
    print('wrote ' + out + ': %d rows over %d species (%d level-up, %d TM)' % (total, len(learn), lv, total - lv))
    if missing:
        print('nobody learns:', sorted(missing))

if __name__ == '__main__':
    main()
